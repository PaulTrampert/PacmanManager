// Builds pacman package files for the end-to-end tests, so a test can upload a package of any size
// without a multi-megabyte fixture committed to the repository.
import { randomBytes } from "node:crypto";
import { gzipSync } from "node:zlib";

/** What {@link buildPackage} writes into a package's `.PKGINFO`, and how large it makes it. */
export interface PackageSpec {
  /** The package's `pkgname`. */
  name: string;
  /** The package's full version, `pkgver-pkgrel`. */
  version: string;
  /** The package's `arch`; `x86_64` by default. */
  arch?: string;
  /**
   * The number of random bytes in the package's one payload file. Random bytes do not compress, so
   * the package file is at least this large.
   */
  payloadBytes: number;
}

const blockSize = 512;

/** A tar archive entry: a regular file with its contents, or a directory. */
type TarEntry =
  | { type: "file"; path: string; contents: Uint8Array }
  | { type: "directory"; path: string };

/** Writes `value` into `header` at `offset` as a NUL-terminated octal number `length` bytes wide. */
function writeOctal(
  header: Buffer,
  offset: number,
  length: number,
  value: number,
): void {
  header.write(
    value.toString(8).padStart(length - 1, "0") + "\0",
    offset,
    length,
    "ascii",
  );
}

/** One ustar header block for `entry`. */
function tarHeader(entry: TarEntry, mtime: number): Buffer {
  const header = Buffer.alloc(blockSize);
  const size = entry.type === "file" ? entry.contents.length : 0;
  header.write(entry.path, 0, 100, "utf8");
  writeOctal(header, 100, 8, entry.type === "file" ? 0o644 : 0o755);
  writeOctal(header, 108, 8, 0); // uid
  writeOctal(header, 116, 8, 0); // gid
  writeOctal(header, 124, 12, size);
  writeOctal(header, 136, 12, mtime);
  header.write(entry.type === "file" ? "0" : "5", 156, 1, "ascii");
  header.write("ustar\0", 257, 6, "ascii");
  header.write("00", 263, 2, "ascii");
  header.write("root", 265, 32, "ascii");
  header.write("root", 297, 32, "ascii");

  // The checksum is summed with its own field taken as eight spaces.
  header.fill(" ", 148, 156, "ascii");
  const checksum = header.reduce((sum, byte) => sum + byte, 0);
  header.write(checksum.toString(8).padStart(6, "0") + "\0 ", 148, 8, "ascii");
  return header;
}

/** An uncompressed ustar archive of `entries`, in order. */
function tar(entries: readonly TarEntry[], mtime: number): Buffer {
  const parts: Uint8Array[] = [];
  for (const entry of entries) {
    parts.push(tarHeader(entry, mtime));
    if (entry.type === "file") {
      parts.push(entry.contents);
      const padding =
        (blockSize - (entry.contents.length % blockSize)) % blockSize;
      parts.push(Buffer.alloc(padding));
    }
  }
  // The end of the archive: two empty blocks.
  parts.push(Buffer.alloc(blockSize * 2));
  return Buffer.concat(parts);
}

/**
 * A gzip-compressed pacman package (`.pkg.tar.gz`) for `spec`: a `.PKGINFO` naming the package, and
 * one payload file of random bytes under `usr/share/<name>/`.
 */
export function buildPackage(spec: PackageSpec): Buffer {
  const { name, version, arch = "x86_64", payloadBytes } = spec;
  const builddate = Math.floor(Date.now() / 1000);
  const pkginfo = [
    "# Generated by pacmanmanager-web/e2e/packages.ts",
    `pkgname = ${name}`,
    `pkgbase = ${name}`,
    `pkgver = ${version}`,
    "pkgdesc = Package built by the PacmanManager end-to-end tests",
    `builddate = ${builddate}`,
    "packager = PacmanManager end-to-end tests",
    `size = ${payloadBytes}`,
    `arch = ${arch}`,
    "license = MIT",
    "",
  ].join("\n");

  const archive = tar(
    [
      { type: "file", path: ".PKGINFO", contents: Buffer.from(pkginfo) },
      { type: "directory", path: "usr/" },
      { type: "directory", path: "usr/share/" },
      { type: "directory", path: `usr/share/${name}/` },
      {
        type: "file",
        path: `usr/share/${name}/payload`,
        contents: randomBytes(payloadBytes),
      },
    ],
    builddate,
  );

  // Level 0 stores the archive rather than compressing it: the payload is random and would not
  // compress anyway, and storing it is quick however large it is.
  return gzipSync(archive, { level: 0 });
}
